// The frame the map is drawn into: everything between these lon/lat bounds.
const BOX = { lon0: -170, lon1: 180, lat0: -52, lat1: 76 };

function projector(x, y, w, h) {
  const sx = w / (BOX.lon1 - BOX.lon0), sy = h / (BOX.lat1 - BOX.lat0);
  return (lon, lat) => [x + (lon - BOX.lon0) * sx, y + (BOX.lat1 - lat) * sy];
}

